// Regression coverage for the full-screen collection menu and Okinawa catalogue.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const dir = path.join(__dirname, '../personal/travel/map');
const html = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
const pause = () => new Promise(r => setTimeout(r, 30));
(async () => {
  const dom = new JSDOM(html, {url:'http://localhost/personal/travel/map/?category=okinawa', runScripts:'outside-only', pretendToBeVisual:true});
  const w = dom.window, d = w.document, $ = s => d.querySelector(s);
  const errors = [];
  w.addEventListener('error', e => errors.push(e.message));
  w.matchMedia = () => ({matches:false, addEventListener(){}, removeEventListener(){}});
  w.Element.prototype.scrollIntoView = () => {};
  w.HTMLDialogElement.prototype.showModal = function(){ this.open = true; };
  w.HTMLDialogElement.prototype.close = function(){ this.open = false; };
  w.localStorage.setItem('okinawa-visited-v2', JSON.stringify(['churaumi','shuri']));
  w.localStorage.setItem('eva.travel.stamp-atlas.v1', JSON.stringify({version:1,visits:{'okinawa:shuri':['2024-03']},customCities:[]}));
  // Stamps are visible only to a signed-in traveller: restore a local session.
  const gateHash = 'a'.repeat(64);
  w.localStorage.setItem('eva.travel.atlas.session.v1', JSON.stringify({hash:gateHash, at:new Date().toISOString()}));
  w.TravelAtlasConfig = {supabaseUrl:'',supabaseAnonKey:'',demoMode:false,localGate:{name:'Test',passphraseHash:gateHash}};
  for (const f of ['account.js','palette.js','world.js','places.js','okinawa-places.js','us-states.js','jp-admin.js','stamp-art.js','app.js']) w.eval(fs.readFileSync(path.join(dir,f),'utf8'));
  await pause();
  assert.deepEqual(errors, []);
  assert.equal(d.body.dataset.atlasTheme, 'okinawa');
  assert.equal($('#board-total').textContent, '49');
  assert.equal($('#board-visited').textContent, '1');
  assert.equal($('#place-name').textContent, '美麗海水族館');
  assert.match($('#legacy-note').textContent, /未記錄月份/);
  assert.equal($('#legacy-note').hidden, false);
  assert.equal($('#place-list').querySelectorAll('.place-item').length, 49);
  assert.match($('#place-list [data-place="shuri"]').textContent, /舊清單/);
  assert.equal($('#tab-okinawa').getAttribute('aria-current'), 'true');
  $('#collection-menu-button').click();
  assert.equal($('#collection-menu').open, true);
  $('#tab-cities').click();
  assert.equal($('#collection-menu').open, false);
  assert.equal(d.body.dataset.atlasTheme, 'cities');
  assert.equal($('#board-title').textContent, '世界主要城市');
  $('#collection-inline').click();
  $('#tab-okinawa').click();
  $('#region-controls [data-region="naha"]').click();
  assert([...d.querySelectorAll('#place-list .place-item')].length < 49);
  $('#place-search').value = '首里';
  $('#place-search').dispatchEvent(new w.Event('input', {bubbles:true}));
  assert($('#place-list [data-place="shuri"]'));
  $('#place-list [data-place="shuri"]').click();
  assert.equal($('#place-name').textContent, '首里城');
  assert.equal($('#history-count').textContent, '1 枚戳章');
  assert.equal(JSON.parse(w.localStorage.getItem('eva.travel.stamp-atlas.v1')).visits['okinawa:shuri'][0], '2024-03');
  assert.deepEqual(JSON.parse(w.localStorage.getItem('okinawa-visited-v2')), ['churaumi','shuri']);
  assert.deepEqual(errors, []);
  dom.window.close();
  console.log('PASS Okinawa: deep link, 49 places, legacy reminder, saved stamps, full-page menu, regions and search');
})().catch(e => { console.error(e); process.exitCode = 1; });
